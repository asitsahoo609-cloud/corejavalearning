package shauryax.addition;

public class AddfloatNumber {

    public void addition(){

        float a = 20.3f;
        float b = 40.2f;
        float c = a + b;
        System.out.println("addition of two float number is " + c);

    }
    public void additionByParameter(float f, float g){

        float x = f;
        float y = g;
        float z = x + y;
        System.out.println("addition of two float number is " + z);



    }
    public float addtionAndReturnValue(){

        float t = 20.3f;
        float r = 60.4f;
        float p = t + r;
        return p;


    }
    public float additionByParameterAndReturnValue(float j, float l){

        float u = j;
        float r = l;
        float i = u + r;
        return i;


    }
}

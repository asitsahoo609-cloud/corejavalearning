package shauryax.addition;

public class AdddoubleNumber {

    public void addition(){
        double a = 60.5d;
        double b = 30.5d;
        double c = a + b;
        System.out.println("addition of two double number is " + c);


    }
    public void additionByParameter(double d, double r){
        double g = d;
        double f = r;
        double p = g + f;
        System.out.println("addition of two double number is " + p);


    }
    public double addtionAndReturnValue(){
        double r = 25.5f;
        double s = 25.5f;
        double t = r + s;
        return t;


    }
    public double additionByParameterAndReturnValue(double u, double h){
        double e = u;
        double g = h;
        double s = e + g;
        return s;


    }

}

package shauryax.subtraction;

public class SublongNumber {
  public void subtwolongnum(){
        long a = 34l;
        long b = 45l;
        long c = a - b;
        System.out.println("Value of two sublong numbers " +c);
}
    public void subtwolongnumByParameter(long e, long s){
        long g = e;
        long l = s;
        long y = g - l;
        System.out.println("Value of two sublong numbers " +y);
    }
    public long subAndReturnValue(){
        long x = 35l;
        long y = 25l;
        long z = x - y;
        return z;

    }
    public long subAndReturnValueByParameter(long g, long h){
        long i = g;
        long r = h;
        long k = i - r;
        return k;

    }
}

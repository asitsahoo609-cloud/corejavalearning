package shauryax.subtraction;

public class SubintNumber {
    public void subtractionwoint(){
        int a = 60;
        int b = 50;
        int c = a - b;
        System.out.println("sub of two number is "+c);

    }
    public void subByParameter(int k,  int l){
        int t = k;
        int q = l;
        int r = t - q;
        System.out.println("parameter addition of two number is  "+ r);
    }

    public int subAndReturnValue(){
        int x = 15;
        int y = 6;
        int z = x - y;
        return z;
    }

    public int subByParameterAndReturnValue(int u, int v){
        int o = u;
        int w = v;
        int n = o - w;
        return n;
    }

}

package shauryax.Divison;

public class DivTwodoubleNumbers {


    public void divison(){
        double a = 35.28f;
        double b = 7.4f;
        double c = a / b;
        System.out.println("value of div two double num" +c);

    }
    public void divisonByParamter(double j, double k){
        double x = j;
        double y = k;
        double z = x / y;
        System.out.println("value of div two double num" +z);

    }


    public double divAndReturnValue(){
        double m = 40.4f;
        double n = 4.2f;
        double k = m / n;
        return k;

    }

    public double divAndReturnValueByParameter(double p, double q){
        double j = p;
        double k = q;
        double n = j / k;
        return k;


    }


}
